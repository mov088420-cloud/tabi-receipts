import {test,expect} from '@playwright/test';
test('real browser OCR uses only local assets and works offline',async({page,context})=>{
 const external:string[]=[];
 const methods:string[]=[];const errors:string[]=[];
 page.on('pageerror',e=>errors.push(e.message));
 context.on('request',r=>{methods.push(r.method());if(/^https?:/.test(r.url())&&!r.url().startsWith('http://127.0.0.1:4173/'))external.push(r.url());});
 await page.goto('/');
 await expect(page.getByText('オフライン準備完了',{exact:true})).toBeVisible({timeout:60_000});
 await page.screenshot({path:'test-results/home-mobile.png',fullPage:true});
 await context.setOffline(true);
 await page.reload();
 await page.getByRole('button',{name:'読み取り',exact:true}).click();
 await page.getByLabel('画像を選ぶ',{exact:true}).setInputFiles('tests/fixtures/receipt.png');
 await page.getByRole('button',{name:'読み取り開始',exact:true}).click();
 await page.getByText('認識したテキスト（一時表示）').click();
 await expect(page.getByLabel('OCR結果')).toHaveValue(/EXAMPLE GARDEN CAFE/,{timeout:150_000});
 const text=await page.getByLabel('OCR結果').inputValue();
 expect(text).toContain('17.99'); expect(text).toContain('4242'); expect(text).toContain('06/11/2026');
 expect(external).toEqual([]);
 console.log('OCR BENCHMARK',await page.locator('.metrics').innerText());
 await page.screenshot({path:'test-results/phase1.png',fullPage:true});
 await expect(page.getByLabel('店舗名',{exact:true})).toHaveValue('EXAMPLE GARDEN CAFE');
 await expect(page.getByLabel('支払金額',{exact:true})).toHaveValue('17.99');
 await expect(page.getByLabel('カード下4桁',{exact:true})).toHaveValue('4242');
 await page.getByLabel('金額・通貨・支払者を原本と照合しました').check();
 await page.getByRole('button',{name:'確認して保存',exact:true}).click();
 await expect(page.getByRole('button',{name:/EXAMPLE GARDEN CAFE/})).toBeVisible();
 await page.reload();
 await expect(page.getByRole('button',{name:/EXAMPLE GARDEN CAFE/})).toBeVisible();
 const records=await page.evaluate(()=>new Promise<any[]>((resolve,reject)=>{const r=indexedDB.open('tabi-receipts');r.onsuccess=()=>{const db=r.result;const get=db.transaction('receipts').objectStore('receipts').getAll();get.onsuccess=()=>{resolve(get.result);db.close();};get.onerror=()=>reject(get.error);};}));
 expect(records).toHaveLength(1);expect(records[0]).not.toHaveProperty('image');expect(records[0]).not.toHaveProperty('text');
 expect(external).toEqual([]);expect(new Set(methods)).toEqual(new Set(['GET']));expect(errors).toEqual([]);
});
